// ============================================================================
// 通用位置式 PID 控制器
// PID_Core.v
// ============================================================================
//
// 【功能介绍】
// 1. 本模块实现一个通用的位置式 PID 控制器：
//
//          Error = Target - Feedback
//
//          P = Kp * Error
//
//          I = I + Ki * Error
//
//          D = Kd * (Error - LastError)
//
//          Output = P + I + D
//
// 2. 本模块仅负责 PID 数学运算，不包含：
//      - 电机控制
//      - PWM
//      - 编码器
//      - TB6612
//      - 电机死区
//      - 最小启动PWM
//      - 角度/转速转换
//
//    因此可以重复用于：
//      - 电机位置环
//      - 电机速度环
//      - 倒立摆角度环
//      - 航向环
//      - 其他闭环控制
//
//
// ============================================================================
// 【数据格式】
//
// 1. target / feedback
//
//      signed [31:0]
//
//    为普通有符号整数，不使用Q格式。
//
//    例如编码器：
//
//      target   = 102
//      feedback = 80
//
//      error = 22
//
//
// --------------------------------------------------------------------------
// 2. Kp / Ki / Kd
//
//    使用32位有符号 Q16.16 定点数。
//
//    转换关系：
//
//      FPGA_Value = Real_Value * 65536
//
//    例如：
//
//      Kp = 1.0
//          -> 65536
//
//      Kp = 5.0
//          -> 327680
//
//      Kp = 2.5
//          -> 163840
//
//      Ki = 0.01
//          -> 655
//
//      Kd = 20.0
//          -> 1310720
//
//
//    所以以后可以直接通过 VIO / UART / VOFA
//    修改 kp_q / ki_q / kd_q，实现在线调参。
//
//
// ============================================================================
// 【关于Ki和Kd的重要说明】
//
// 本模块内部不参与 dt 运算。
//
// 算法直接使用：
//
//      I += Ki * Error
//
//      D  = Kd * (Error - LastError)
//
// 因此这里的 Ki / Kd 是“离散PID系数”。
//
// 如果从传统连续PID参数转换，采样周期为 Ts：
//
//      Ki_FPGA = Ki * Ts
//
//      Kd_FPGA = Kd / Ts
//
// Kp保持不变。
//
// 例如：
//
//      Ts = 5ms = 0.005s
//
// 原始：
//      Kp = 10
//      Ki = 2
//      Kd = 0.1
//
// FPGA离散参数：
//
//      Kp = 10
//
//      Ki = 2 * 0.005
//         = 0.01
//
//      Kd = 0.1 / 0.005
//         = 20
//
// 如果直接通过实验调参，则可以不用转换，
// 直接把 Kp/Ki/Kd 当作本PID模块自己的参数进行调节。
//
//
// ============================================================================
// 【PID更新周期】
//
// pid_tick每出现一个时钟周期高电平，PID计算一次。
//
// 例如：
//
//      FPGA CLK = 50MHz
//      PID周期  = 5ms
//
// 则每：
//
//      250000 个 clk
//
// 产生一次 pid_tick。
//
// 本模块不会自行生成PID周期。
// pid_tick由外部Timer模块产生。
//
//
// ============================================================================
// 【积分限幅】
//
// i_limit表示：
//
//      I项最终允许贡献的最大控制量
//
// 例如：
//
//      i_limit = 500
//
// 则：
//
//      -500 <= I <= +500
//
// 注意：
//
// 本模块限制的是“I项输出本身”，
// 而不是传统实现中的 SumError。
//
// 这种方式更加直观，也更适合FPGA定点运算。
//
//
// ============================================================================
// 【输出限幅】
//
// out_max / out_min也是普通整数。
//
// 例如电机控制：
//
//      out_max = +2500
//      out_min = -2500
//
// 那么最终：
//
//      -2500 <= pid_out <= +2500
//
// 但是PID模块本身并不知道2500代表PWM。
// 对其他应用，也可以设置：
//
//      -1000 ~ +1000
//
//      -500 ~ +500
//
// 等任意范围。
//
//
// ============================================================================
// 【pid_en】
//
// pid_en = 0：
//
//      PID停止工作
//      pid_out = 0
//      积分清零
//
// 同时会持续同步当前Error，
// 防止重新开启PID时D项突然产生巨大跳变。
//
//
// ============================================================================
// 【pid_clear】
//
// pid_clear = 1：
//
//      清除积分
//      清除历史误差状态
//      pid_out = 0
//
// 可以在：
//
//      - 修改PID参数之后
//      - 修改目标模式之后
//      - 系统重新开始控制时
//
// 给一个clk周期的高电平。
//
//
// ============================================================================
// 【调试输出】
//
// error_out
// p_out
// i_out
// d_out
//
// 都已经转换回普通整数，方便：
//
//      ILA
//      VIO
//      UART
//      VOFA
//
// 实时观察PID状态。
//
//
// ============================================================================

// 本工程分拍版：接受pid_tick后8个clk完成（50MHz为160ns），pid_valid标记结果。
// 忙时忽略新tick；复位/clear/禁用取消未完成运算。接口、位宽及Q16.16规则保留。
module PID_Core
(
    input  wire                         clk,
    input  wire                         rst_n,

    // ========================================================
    // PID控制
    // ========================================================

    input  wire                         pid_en,

    // PID内部状态清零
    input  wire                         pid_clear,

    // PID更新脉冲
    input  wire                         pid_tick,


    // ========================================================
    // 目标值 / 反馈值
    // 普通有符号整数
    // ========================================================

    input  wire signed [31:0]           target,

    input  wire signed [31:0]           feedback,


    // ========================================================
    // PID参数
    //
    // Q16.16格式
    // ========================================================

    input  wire signed [31:0]           kp_q,

    input  wire signed [31:0]           ki_q,

    input  wire signed [31:0]           kd_q,


    // ========================================================
    // PID输出限幅
    //
    // 普通整数
    // ========================================================

    input  wire signed [31:0]           out_max,

    input  wire signed [31:0]           out_min,


    // ========================================================
    // 积分输出限幅
    //
    // 输入正数
    //
    // 例如：
    // i_limit = 500
    //
    // I项范围：
    // -500 ~ +500
    // ========================================================

    input  wire signed [31:0]           i_limit,


    // ========================================================
    // PID最终输出
    //
    // 普通有符号整数
    // ========================================================

    output reg signed [31:0]            pid_out,


    // ========================================================
    // 调试输出
    //
    // 普通整数
    // ========================================================

    output reg signed [32:0]            error_out,

    output reg signed [31:0]            p_out,

    output reg signed [31:0]            i_out,

    output reg signed [31:0]            d_out,


    // 每完成一次PID计算产生一个clk宽度脉冲
    output reg                          pid_valid
);


// ============================================================================
// Q格式配置
// ============================================================================

localparam integer Q_FRAC_BITS = 16;


// ============================================================================
// Error
//
// target / feedback为32位
//
// 两个32位有符号数相减，使用33位保存，防止溢出。
// ============================================================================

wire signed [32:0] target_ext;

wire signed [32:0] feedback_ext;


assign target_ext =
{
    target[31],
    target
};


assign feedback_ext =
{
    feedback[31],
    feedback
};


// 当前误差
wire signed [32:0] error_now;

assign error_now =
    target_ext - feedback_ext;


// ============================================================================
// 上一次误差
// ============================================================================

reg signed [32:0] last_error;

// 各阶段只保存本次运算的中间值；历史积分和误差在COMMIT统一更新。
localparam [3:0] IDLE=0, DELTA=1, MULTIPLY=2, I_ADD=3, I_CLAMP=4,
                 PI_ADD=5, PID_ADD=6, OUT_CLAMP=7, COMMIT=8;
reg [3:0] stage;
reg signed [32:0] error_work, last_error_work;
reg signed [31:0] kp_work, ki_work, kd_work;
reg signed [31:0] i_limit_work, out_max_work, out_min_work;
reg signed [71:0] pi_sum_q;


// ============================================================================
// Error变化量
//
// 33位Error再次相减，使用34位保存。
// ============================================================================

wire signed [33:0] error_now_ext;

wire signed [33:0] last_error_ext;


assign error_now_ext =
{
    error_work[32],
    error_work
};


assign last_error_ext =
{
    last_error_work[32],
    last_error_work
};


reg signed [33:0] delta_error;

// 对应运算在下方状态机的独立时钟阶段完成。


// ============================================================================
// P项乘法
//
// Error:
//      33bit整数
//
// Kp:
//      32bit Q16.16
//
// 乘法结果：
//      65bit
//
// 并且仍然具有16位小数。
// ============================================================================

reg signed [64:0] p_mult_q;

// 对应运算在下方状态机的独立时钟阶段完成。


// ============================================================================
// I项本次增量
//
// Ki * Error
//
// 结果也是Q16.16。
// ============================================================================

reg signed [64:0] i_increment_q;

// 对应运算在下方状态机的独立时钟阶段完成。


// ============================================================================
// D项
//
// delta_error:
//      34bit
//
// Kd:
//      32bit
//
// 结果：
//      66bit
// ============================================================================

reg signed [65:0] d_mult_q;

// 对应运算在下方状态机的独立时钟阶段完成。


// ============================================================================
// 内部统一使用72位进行运算
//
// 给P/I/D以及累加留出足够的余量。
// ============================================================================

wire signed [71:0] p_term_q;

wire signed [71:0] i_increment_ext_q;

wire signed [71:0] d_term_q;


assign p_term_q =
{
    {7{p_mult_q[64]}},
    p_mult_q
};


assign i_increment_ext_q =
{
    {7{i_increment_q[64]}},
    i_increment_q
};


assign d_term_q =
{
    {6{d_mult_q[65]}},
    d_mult_q
};


// ============================================================================
// 积分器
//
// 内部始终保持Q16.16。
// ============================================================================

reg signed [71:0] i_term_q;


// ============================================================================
// 将i_limit从普通整数转换成内部Q16.16
//
// 例如：
//
// i_limit = 500
//
// 内部：
//
// 500 << 16
// ============================================================================

wire signed [71:0] i_limit_ext;

assign i_limit_ext =
{
    {40{i_limit_work[31]}},
    i_limit_work
};


wire signed [71:0] i_max_q;

wire signed [71:0] i_min_q;


assign i_max_q =
    i_limit_ext <<< Q_FRAC_BITS;


assign i_min_q =
    -i_max_q;


// ============================================================================
// 计算下一次积分值
// ============================================================================

reg signed [71:0] i_candidate_q;

// 对应运算在下方状态机的独立时钟阶段完成。


// ============================================================================
// 积分限幅
// ============================================================================

reg signed [71:0] i_next_q;


// 对应运算在下方状态机的独立时钟阶段完成。


// ============================================================================
// PID求和
//
// P + I + D
//
// 仍然保持Q16.16。
// ============================================================================

reg signed [71:0] pid_sum_q;


// 对应运算在下方状态机的独立时钟阶段完成。


// ============================================================================
// 输出上下限转换成Q16.16
// ============================================================================

wire signed [71:0] out_max_ext;

wire signed [71:0] out_min_ext;


assign out_max_ext =
{
    {40{out_max_work[31]}},
    out_max_work
};


assign out_min_ext =
{
    {40{out_min_work[31]}},
    out_min_work
};


wire signed [71:0] out_max_q;

wire signed [71:0] out_min_q;


assign out_max_q =
    out_max_ext <<< Q_FRAC_BITS;


assign out_min_q =
    out_min_ext <<< Q_FRAC_BITS;


// ============================================================================
// PID输出限幅
//
// 注意：
//
// 在Q格式内部就进行限幅，
// 然后最后再转换成整数。
// ============================================================================

reg signed [71:0] pid_limited_q;


// 对应运算在下方状态机的独立时钟阶段完成。


// ============================================================================
// Q16.16 -> 普通整数
//
// 算术右移16位。
// ============================================================================

wire signed [71:0] pid_integer_ext;

wire signed [71:0] p_integer_ext;

wire signed [71:0] i_integer_ext;

wire signed [71:0] d_integer_ext;


assign pid_integer_ext =
    pid_limited_q >>> Q_FRAC_BITS;


assign p_integer_ext =
    p_term_q >>> Q_FRAC_BITS;


assign i_integer_ext =
    i_next_q >>> Q_FRAC_BITS;


assign d_integer_ext =
    d_term_q >>> Q_FRAC_BITS;


// ============================================================================
// PID状态更新
// ============================================================================

always @(posedge clk)
begin

    // ========================================================================
    // 系统复位
    // ========================================================================

    if (!rst_n)
    begin

        stage <= IDLE;
        error_work <= 0; last_error_work <= 0;
        kp_work <= 0; ki_work <= 0; kd_work <= 0;
        i_limit_work <= 0; out_max_work <= 0; out_min_work <= 0;
        delta_error <= 0; p_mult_q <= 0; i_increment_q <= 0; d_mult_q <= 0;
        i_candidate_q <= 0; i_next_q <= 0; pi_sum_q <= 0;
        pid_sum_q <= 0; pid_limited_q <= 0;

        last_error <= 33'sd0;

        i_term_q <= 72'sd0;

        pid_out <= 32'sd0;

        error_out <= 33'sd0;

        p_out <= 32'sd0;

        i_out <= 32'sd0;

        d_out <= 32'sd0;

        pid_valid <= 1'b0;

    end


    else
    begin

        // 默认pid_valid只维持一个clk
        pid_valid <= 1'b0;


        // ====================================================================
        // 手动清PID
        // ====================================================================

        if (pid_clear)
        begin
            stage <= IDLE;

            // 记录当前误差
            //
            // 这样下一次启动时：
            //
            // Error - LastError ≈ 0
            //
            // 可以避免D项突然跳变。

            last_error <= error_now;


            // 积分清零
            i_term_q <= 72'sd0;


            // PID输出清零
            pid_out <= 32'sd0;


            error_out <= error_now;

            p_out <= 32'sd0;

            i_out <= 32'sd0;

            d_out <= 32'sd0;

        end


        // ====================================================================
        // PID关闭
        // ====================================================================

        else if (!pid_en)
        begin
            stage <= IDLE;

            // 持续同步当前Error
            //
            // 防止重新开启时D项产生巨大冲击。

            last_error <= error_now;


            // PID关闭时积分清零
            i_term_q <= 72'sd0;


            // 输出强制0
            pid_out <= 32'sd0;


            error_out <= error_now;

            p_out <= 32'sd0;

            i_out <= 32'sd0;

            d_out <= 32'sd0;

        end


        // ====================================================================
        // PID更新
        // ====================================================================

        else
        begin
            case (stage)
                IDLE: if (pid_tick) begin
                    error_work <= error_now;
                    last_error_work <= last_error;
                    kp_work <= kp_q; ki_work <= ki_q; kd_work <= kd_q;
                    i_limit_work <= i_limit;
                    out_max_work <= out_max; out_min_work <= out_min;
                    stage <= DELTA;
                end
                DELTA: begin
                    delta_error <= error_now_ext - last_error_ext;
                    stage <= MULTIPLY;
                end
                MULTIPLY: begin
                    p_mult_q <= $signed(error_work) * $signed(kp_work);
                    i_increment_q <= $signed(error_work) * $signed(ki_work);
                    d_mult_q <= $signed(delta_error) * $signed(kd_work);
                    stage <= I_ADD;
                end
                I_ADD: begin
                    i_candidate_q <= i_term_q + i_increment_ext_q;
                    stage <= I_CLAMP;
                end
                I_CLAMP: begin
                    i_next_q <= (i_candidate_q > i_max_q) ? i_max_q :
                                (i_candidate_q < i_min_q) ? i_min_q : i_candidate_q;
                    stage <= PI_ADD;
                end
                PI_ADD: begin
                    pi_sum_q <= p_term_q + i_next_q;
                    stage <= PID_ADD;
                end
                PID_ADD: begin
                    pid_sum_q <= pi_sum_q + d_term_q;
                    stage <= OUT_CLAMP;
                end
                OUT_CLAMP: begin
                    pid_limited_q <= (pid_sum_q > out_max_q) ? out_max_q :
                                     (pid_sum_q < out_min_q) ? out_min_q : pid_sum_q;
                    stage <= COMMIT;
                end
                COMMIT: begin

            // ---------------------------------------------------------------
            // 保存Error
            // ---------------------------------------------------------------

            error_out <= error_work;


            // ---------------------------------------------------------------
            // 保存本次Error
            //
            // 下一次PID运算用于D项。
            // ---------------------------------------------------------------

            last_error <= error_work;


            // ---------------------------------------------------------------
            // 更新积分器
            // ---------------------------------------------------------------

            i_term_q <= i_next_q;


            // ---------------------------------------------------------------
            // 最终PID输出
            // ---------------------------------------------------------------

            pid_out <= pid_integer_ext[31:0];


            // ---------------------------------------------------------------
            // 调试输出
            // ---------------------------------------------------------------

            p_out <= p_integer_ext[31:0];

            i_out <= i_integer_ext[31:0];

            d_out <= d_integer_ext[31:0];


            // ---------------------------------------------------------------
            // 本次PID计算完成
            // ---------------------------------------------------------------

            pid_valid <= 1'b1;
            stage <= IDLE;

                end
                default: stage <= IDLE;
            endcase
        end

    end

end


endmodule